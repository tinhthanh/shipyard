#!/usr/bin/env python3
"""The fork's Homebrew formulas for one release (fork-release.yml).

    scripts/homebrew-formulas.py TAG REPO CHECKSUMS OUTDIR

TAG is the release's tag (v0.3.31-fork.3), REPO this repository
(tinhthanh/shipyard), CHECKSUMS the release's checksums.txt. Writes
OUTDIR/Formula/vetgo.rb (berth, the CLI and laptop agent, with the berthd
builds it puts on boxes) and OUTDIR/Formula/berthd.rb (the box daemon), for
the tap at github.com/tinhthanh/homebrew-tap:

    brew trust tinhthanh/tap      # Homebrew asks this of any tap not its own
    brew install tinhthanh/tap/vetgo
    brew install tinhthanh/tap/berthd
"""

import pathlib
import sys


def sums(path):
    out = {}
    for line in pathlib.Path(path).read_text().splitlines():
        parts = line.split()
        if len(parts) == 2:
            out[parts[1]] = parts[0]
    return out


def url(repo, tag, name):
    return f"https://github.com/{repo}/releases/download/{tag}/{name}"


def platforms(repo, tag, s, prog, mac_extra="", indent="  "):
    """on_macos/on_linux blocks with each architecture's archive, and
    mac_extra (more lines) in on_macos."""
    out = []
    for os_name, block in (("darwin", "on_macos"), ("linux", "on_linux")):
        out.append(f"{indent}{block} do")
        for arch, cpu in (("arm64", "on_arm"), ("amd64", "on_intel")):
            name = f"{prog}-{os_name}-{arch}.tar.gz"
            if name not in s:
                raise SystemExit(f"checksums.txt has no {name}")
            out += [f"{indent}  {cpu} do", f'{indent}    url "{url(repo, tag, name)}"', f'{indent}    sha256 "{s[name]}"', f"{indent}  end"]
        if os_name == "darwin" and mac_extra:
            out += ["", mac_extra]
        out.append(f"{indent}end")
    return "\n".join(out)


def vetgo(repo, tag, s):
    version = tag.removeprefix("v")
    darwin_daemons = "    # The berthd builds `berth upgrade` puts on Mac boxes; the Linux ones\n    # come in berth's own archive.\n" + "\n".join(
        f'''    resource "berthd-darwin-{arch}" do
      url "{url(repo, tag, f"berthd-darwin-{arch}.tar.gz")}"
      sha256 "{s[f"berthd-darwin-{arch}.tar.gz"]}"
    end''' for arch in ("arm64", "amd64"))
    return f'''# Generated by scripts/homebrew-formulas.py in {repo} for {tag}.
class Vetgo < Formula
  desc "Run coding agents on your own boxes: the berth CLI and laptop agent"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

{platforms(repo, tag, s, "berth", darwin_daemons)}

  def install
    # berth looks beside its own file (through the link in bin) for the
    # berthd and tmux builds it uploads to boxes.
    libexec.install Dir["*"]
    if OS.mac?
      %w[arm64 amd64].each do |arch|
        resource("berthd-darwin-#{{arch}}").stage {{ libexec.install "berthd" => "berthd-darwin-#{{arch}}" }}
      end
    end
    bin.install_symlink libexec/"berth"
  end

  def caveats
    <<~EOS
      Start the laptop agent, and have it start when you log in:
        berth agent install
      Add a box: berth add ssh USER@HOST (see berth help).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/berth version")
  end
end
'''


def berthd(repo, tag, s):
    version = tag.removeprefix("v")
    return f'''# Generated by scripts/homebrew-formulas.py in {repo} for {tag}.
class Berthd < Formula
  desc "Box daemon for Vetgo: runs coding agents, terminals and services"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

{platforms(repo, tag, s, "berthd")}

  def install
    bin.install "berthd"
  end

  def caveats
    <<~EOS
      Install berthd as your user's service and pair a laptop with it:
        berthd install
      It prints a pairing link to open on the laptop.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/berthd version")
  end
end
'''


def main(argv):
    if len(argv) != 5:
        raise SystemExit(__doc__)
    tag, repo, checksums, outdir = argv[1:]
    s = sums(checksums)
    formula = pathlib.Path(outdir) / "Formula"
    formula.mkdir(parents=True, exist_ok=True)
    (formula / "vetgo.rb").write_text(vetgo(repo, tag, s))
    (formula / "berthd.rb").write_text(berthd(repo, tag, s))


if __name__ == "__main__":
    main(sys.argv)
